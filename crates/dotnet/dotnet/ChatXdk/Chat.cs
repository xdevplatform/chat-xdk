        /// <summary>
        /// Get the fingerprint of the loaded identity public key.
        /// Returns a URL-safe base64 SHA-256 of the SPKI-encoded key —
        /// suitable for out-of-band verification by the user.
        /// </summary>
        public string GetPublicKeyFingerprint()
        {
            ThrowIfDisposed();
            var fingerprint = ConsumeResult(NativeMethods.chat_xdk_get_public_key_fingerprint(_handle));
            GC.KeepAlive(this);
            return fingerprint;
        }

        /// <summary>
        /// Export private keys as raw bytes for a secure backup.
        /// Returns <see langword="null"/> if the SDK is locked.
        /// Warning: These are raw secret key bytes — store with extreme care.
        /// </summary>
        public byte[]? ExportKeys()
        {
            ThrowIfDisposed();
            // Mirrors core's export requirement: identity key present
            // (signing key optional, giving a 32-byte export).
            if (!HasIdentityKey) return null;
            var b64 = ConsumeResult(NativeMethods.chat_xdk_export_keys(_handle));
            GC.KeepAlive(this);
            if (string.IsNullOrEmpty(b64)) return null;
            return Convert.FromBase64String(b64);
        }

        /// <summary>
        /// Import private keys from a byte array produced by <see cref="ExportKeys"/>.
        /// Accepts 32 bytes (identity only) or 64 bytes (identity + signing).
        /// When <paramref name="version"/> is given, the public key version the keys
        /// were registered under is recorded as well, so participant-key filtering
        /// and the session signing-key version are set in one call.
        /// </summary>
        public void ImportKeys(byte[] keys, string? version = null)
        {
            ThrowIfDisposed();
            if (version != null)
            {
                var ver = Utf8Z(version);
                // A zero-length array pins to a null pointer on some CLRs; the
                // native side treats NULL + length 0 as an empty key blob.
                if (keys.Length == 0)
                {
                    fixed (byte* verPtr = ver)
                        ConsumeResult(NativeMethods.chat_xdk_import_keys_with_version(_handle, null, 0, verPtr));
                }
                else
                {
                    fixed (byte* keysPtr = keys)
                    fixed (byte* verPtr = ver)
                        ConsumeResult(NativeMethods.chat_xdk_import_keys_with_version(
                            _handle, keysPtr, (nuint)keys.Length, verPtr));
                }
                GC.KeepAlive(this);
                return;
            }
            var b64 = Convert.ToBase64String(keys);
            var b64Bytes = Utf8Z(b64);
            fixed (byte* b64Ptr = b64Bytes)
                ConsumeResult(NativeMethods.chat_xdk_import_keys(_handle, b64Ptr));
            GC.KeepAlive(this);
        }

        // Event decryption

        /// <summary>
        /// Extract and decrypt conversation keys from raw <c>KeyChange</c> event strings.
        /// </summary>
        /// <param name="events">
        /// Base64-encoded raw event strings received from the webhook.
        /// Pass only <c>KeyChange</c> events — other event types are ignored.
        /// </param>
        /// <returns>
        /// Decrypted keys and <see cref="ConversationKeyBundle.LatestVersion"/>.
        /// Pass <see cref="ConversationKeyBundle.Keys"/> (or the whole bundle) to <see cref="DecryptEvent"/>.
        /// </returns>
        public ConversationKeyBundle ExtractConversationKeys(IEnumerable<string> events)
        {
            ThrowIfDisposed();
            var eventsJson = JsonSerializer.Serialize(new List<string>(events), JsonOpts);
            var eventsBytes = Utf8Z(eventsJson);
            string resultJson;
            fixed (byte* eventsPtr = eventsBytes)
                resultJson = ConsumeResult(NativeMethods.chat_xdk_extract_conversation_keys(_handle, eventsPtr));
            GC.KeepAlive(this);

            using var doc = JsonDocument.Parse(resultJson);
            return ParseConversationKeyBundle(doc.RootElement);
        }

        /// <summary>
        /// Decrypt a webhook event and return it as a <see cref="JsonElement"/>.
        /// </summary>
        /// <param name="eventB64">Base64-encoded raw event from the webhook.</param>
        /// <param name="conversationKeys">
        /// Map of version → raw 32-byte key bytes from <see cref="ExtractConversationKeys"/> or
        /// <see cref="DecryptEventsResult.ConversationKeys"/>. Pass <see langword="null"/> (or an empty dict)
        /// for non-message events, or to fall back to the opt-in key cache
        /// (<see cref="SetCacheKeys"/>).
        /// </param>
        /// <param name="signingKeys">
        /// Signing keys for the sender. The SDK picks the matching version automatically.
        /// <see langword="null"/> (or an empty list) falls back to the keys stored via
        /// <see cref="SetSigningKeys"/>; if none are stored either, every signed event
        /// throws under the default reject-unverified policy (only after
        /// <see cref="SetRejectUnverified"/>(false) are such events returned with
        /// <c>verified: false</c>).
        /// </param>
        /// <returns>
        /// A <see cref="JsonElement"/> with a <c>"type"</c> field indicating the event kind
        /// (<c>"Message"</c>, <c>"KeyChange"</c>, <c>"GroupChange"</c>, etc.).
        /// </returns>
        public JsonElement DecryptEvent(
            string eventB64,
            Dictionary<string, byte[]>? conversationKeys = null,
            IEnumerable<SigningKeyEntry>? signingKeys = null)
        {
            ThrowIfDisposed();

            // Serialise conv keys as { "version": "base64", ... }
            var convKeysB64 = new Dictionary<string, string>();
            if (conversationKeys != null)
                foreach (var (version, key) in conversationKeys)
                    convKeysB64[version] = Convert.ToBase64String(key);
            var convKeysJson = JsonSerializer.Serialize(convKeysB64, JsonOpts);

            var signingKeysList = signingKeys != null
                ? new List<SigningKeyEntry>(signingKeys)
                : new List<SigningKeyEntry>();
            var signingKeysJson = JsonSerializer.Serialize(signingKeysList, JsonOpts);

            var eventBytes = Utf8Z(eventB64);
            var convBytes = Utf8Z(convKeysJson);
            var sigBytes = Utf8Z(signingKeysJson);
            string resultJson;
            fixed (byte* evtPtr = eventBytes)
            fixed (byte* convPtr = convBytes)
            fixed (byte* sigPtr = sigBytes)
                resultJson = ConsumeResult(
                    NativeMethods.chat_xdk_decrypt_event(_handle, evtPtr, convPtr, sigPtr));
            GC.KeepAlive(this);

            using var doc = JsonDocument.Parse(resultJson);
            return doc.RootElement.Clone();
        }

        /// <summary>
        /// Decrypt a single event using keys from <see cref="ExtractConversationKeys"/> or
        /// <see cref="DecryptEventsResult.ConversationKeys"/> (uses <see cref="ConversationKeyBundle.Keys"/>).
        /// </summary>
        public JsonElement DecryptEvent(
            string eventB64,
            ConversationKeyBundle? conversationKeys,
            IEnumerable<SigningKeyEntry>? signingKeys = null)
            => DecryptEvent(eventB64, conversationKeys?.Keys, signingKeys);

        /// <summary>
        /// Decrypt a batch of webhook events in one call.
        /// Keys are extracted from <c>KeyChange</c> events in the batch; failures are recorded
        /// in <see cref="DecryptEventsResult.Errors"/> — this method never throws per-event.
        /// Passing <see langword="null"/> (or an empty list) for <paramref name="signingKeys"/>
        /// falls back to the keys stored via <see cref="SetSigningKeys"/>.
        /// </summary>
        public DecryptEventsResult DecryptEvents(
            IEnumerable<string> events,
            IEnumerable<SigningKeyEntry>? signingKeys = null)
        {
            ThrowIfDisposed();
            var eventsJson = JsonSerializer.Serialize(new List<string>(events), JsonOpts);
            var signingKeysList = signingKeys != null
                ? new List<SigningKeyEntry>(signingKeys)
                : new List<SigningKeyEntry>();
            var signingKeysJson = JsonSerializer.Serialize(signingKeysList, JsonOpts);
            var eventsBytes = Utf8Z(eventsJson);
            var sigBytes = Utf8Z(signingKeysJson);
            string resultJson;
            fixed (byte* evPtr = eventsBytes)
            fixed (byte* sigPtr = sigBytes)
                resultJson = ConsumeResult(
                    NativeMethods.chat_xdk_decrypt_events(_handle, evPtr, sigPtr));
            GC.KeepAlive(this);

            using var doc = JsonDocument.Parse(resultJson);
            var root = doc.RootElement;

            var messages = new List<DecryptedMessage>();
            foreach (var el in root.GetProperty("messages").EnumerateArray())
            {
                var eventEl = el.GetProperty("event");
                string? orig = null;
                if (el.TryGetProperty("original_b64", out var ob) && ob.ValueKind == JsonValueKind.String)
                    orig = ob.GetString();
                messages.Add(new DecryptedMessage
                {
                    Event = eventEl.Clone(),
                    OriginalB64 = orig,
                });
            }

            var bundle = ParseConversationKeyBundle(root.GetProperty("conversation_keys"));

            var errors = new Dictionary<string, string>();
            foreach (var prop in root.GetProperty("errors").EnumerateObject())
                errors[prop.Name] = prop.Value.GetString() ?? "";

            return new DecryptEventsResult
            {
                Messages = messages,
                ConversationKeys = bundle,
                Errors = errors,
            };
        }

        /// <summary>
        /// Prepare a signed conversation-key change, ready to send to the X API.
        /// Use this to start a one-to-one or rotate an existing conversation's key
        /// (one-to-one or group). Creating a group or adding members requires a paired
