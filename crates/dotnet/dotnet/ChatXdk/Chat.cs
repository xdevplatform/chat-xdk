using System;
using System.Collections.Generic;
using System.Runtime.InteropServices;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace ChatXdk
{
    /// <summary>
    /// The main X Chat encryption SDK.
    ///
    /// <para>Wraps the Rust <c>chat_xdk_core</c> library via P/Invoke and provides
    /// the operations exposed by the SDK:</para>
    /// <list type="bullet">
    ///   <item>Key generation and Juicebox-backed storage (<see cref="GenerateKeypairs"/>, <see cref="Setup"/>, <see cref="Unlock"/>)</item>
    ///   <item>Event decryption (<see cref="ExtractConversationKeys"/>, <see cref="DecryptEvents"/>, <see cref="DecryptEvent"/>)</item>
    ///   <item>Signed conversation-key changes (<see cref="PrepareConversationKeyChange"/>, <see cref="PrepareGroupCreate"/>, <see cref="PrepareGroupMembersChange"/>)</item>
    ///   <item>Group metadata decryption with the conversation key (<see cref="Decrypt"/>)</item>
    ///   <item>Message / reaction / reply encryption (<see cref="EncryptMessage"/>, etc.)</item>
    ///   <item>File encryption (<see cref="EncryptFile"/>, <see cref="DecryptFile"/>, <see cref="FileEncryptor"/>, <see cref="FileDecryptor"/>)</item>
    ///   <item>Stateless helpers on <see cref="ChatXdkUtilities"/> (base64/hex, MIME, image dimensions)</item>
    /// </list>
    ///
    /// <para>Always <see cref="Dispose"/> the instance when finished to release native resources.</para>
    ///
    /// <para>Its methods may be called from several threads at once; <see cref="Dispose"/>
    /// must not race them.</para>
    /// </summary>
    /// <example>
    /// <code>
    /// using var chat = new Chat(juiceboxConfigJson);
    /// chat.Unlock(pinBytes);
    /// chat.SetIdentity(new SetIdentityParams(myUserId, mySigningKeyVersion)); // session identity, once
    /// chat.SetCacheKeys(true);                                               // opt-in conversation-key cache
    /// chat.SetSigningKeys(participantSigningKeys);                           // default verification keys
    ///
    /// // Decrypt incoming events (keys are cached from verified KeyChange events)
    /// var result = chat.DecryptEvents(new DecryptEventsParams(eventsB64));
    /// var evt = chat.DecryptEvent(new DecryptEventParams(eventB64, result.ConversationKeys.Keys));
    /// Console.WriteLine(evt.GetProperty("type").GetString()); // "Message", "KeyChange", …
    ///
    /// // Send a message — identity and conversation key resolve from the session
    /// var payload = chat.EncryptMessage(new EncryptMessageParams(convId, "Hello from .NET!"));
    /// // The SDK generates the message id; read it back from payload.MessageId.
    /// // POST payload fields to the X API…
    /// </code>
    /// </example>
    public sealed unsafe class Chat : IDisposable
    {
        // Pointer to the native ChatHandle allocated by chat_xdk_new().
        // ChatHandle is generated by csbindgen at the ChatXdk namespace level.
        private ChatHandle* _handle;
        private bool _disposed;

        // Shared JSON options: ignore nulls on write. Property names are
        // snake_case via explicit [JsonPropertyName] attributes on each DTO,
        // not a naming policy here.
        private static readonly JsonSerializerOptions JsonOpts = new()
        {
            DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        };

        /// <summary>
        /// Create a Chat SDK instance without a Juicebox config, which manages its keys with
        /// <see cref="ImportKeys"/> and <see cref="GenerateKeypairs"/> alone or takes its config
        /// later from <see cref="UpdateConfig"/>. Until then <see cref="Setup"/>,
        /// <see cref="Unlock"/>, <see cref="ChangePin"/> and <see cref="Delete"/> throw a
        /// <see cref="ChatXdkException"/> of kind <see cref="ChatXdkErrorKind.InvalidState"/>.
        /// </summary>
        public Chat() : this(null, null, TimeSpan.Zero)
        {
        }

        /// <summary>
        /// Create a Chat SDK instance that keeps its keys in Juicebox, with the Juicebox
        /// configuration JSON the X API returns. <see cref="Setup"/>, <see cref="Unlock"/>,
        /// <see cref="ChangePin"/> and <see cref="Delete"/> use it; <see cref="UpdateConfig"/>
        /// replaces it.
        /// </summary>
        /// <exception cref="ChatXdkException">
        /// The configuration is not a Juicebox config (kind <see cref="ChatXdkErrorKind.InvalidInput"/>),
        /// or is empty or blank (kind <see cref="ChatXdkErrorKind.InvalidState"/>, the error a chat
        /// without a config gives its Juicebox calls).
        /// </exception>
        public Chat(string juiceboxConfigJson) : this(juiceboxConfigJson, null, TimeSpan.Zero)
        {
            ArgumentNullException.ThrowIfNull(juiceboxConfigJson);
        }

        /// <summary>
        /// For this repository's tests: a chat that reads its feature switches from
        /// <paramref name="featureEndpoint"/> within <paramref name="featureTimeout"/>, or
        /// from the default endpoint when it is null.
        /// </summary>
        internal Chat(string? juiceboxConfigJson, string? featureEndpoint, TimeSpan featureTimeout)
        {
            ChatHandle* handle = null;
            var configBytes = juiceboxConfigJson == null ? null : Utf8Z(juiceboxConfigJson);
            fixed (byte* configPtr = configBytes)
                ConsumeResult(NativeMethods.chat_xdk_new(configPtr, &handle));
            _handle = handle;
            if (featureEndpoint != null)
                ConfigureFeatures(featureEndpoint, featureTimeout);
            FeatureFetch.Start(this);
        }

        /// <summary>
        /// Finalizer — ensures the native handle is freed even if <see cref="Dispose"/>
        /// is never called explicitly (e.g. the object is forgotten without <c>using</c>).
        /// An object becomes finalizable as soon as its last use passes — even while
        /// one of its methods is still executing native code — so every method that
        /// passes <c>_handle</c> across the P/Invoke boundary calls
        /// <see cref="GC.KeepAlive(object)"/> on <c>this</c> after the call, keeping
        /// this finalizer from freeing the handle mid-call.
        /// </summary>
        ~Chat() => Dispose(disposing: false);

        /// <inheritdoc/>
        public void Dispose()
        {
            Dispose(disposing: true);
            GC.SuppressFinalize(this);
        }

        private void Dispose(bool disposing)
        {
            // Both the finalizer and Dispose() paths end here.
            // We only need to free the unmanaged handle; there are no managed resources.
            if (!_disposed)
            {
                _disposed = true;
                if (_handle != null)
                {
                    NativeMethods.chat_xdk_free(_handle);
                    _handle = null;
                }
            }
        }

        // Internal helpers

        private void ThrowIfDisposed()
        {
            if (_disposed) throw new ObjectDisposedException(nameof(Chat));
        }

        /// <summary>
        /// Consume a native <see cref="FfiResult"/>: free both pointers,
        /// throw <see cref="ChatXdkException"/> on error, return the data string on success.
        /// Returns an empty string for void-OK results.
        /// </summary>
        internal static string ConsumeResult(FfiResult result)
        {
            // Always marshal both strings before freeing — avoids a double-free
            // if the error branch short-circuits.
            string? data = result.data != null
                ? Marshal.PtrToStringUTF8((IntPtr)result.data)
                : null;
            string? error = result.error != null
                ? Marshal.PtrToStringUTF8((IntPtr)result.error)
                : null;

            if (result.data != null) NativeMethods.chat_xdk_free_string(result.data);
            if (result.error != null) NativeMethods.chat_xdk_free_string(result.error);

            if (error != null) throw ChatXdkException.FromDocument(error);
            return data ?? "";
        }

        /// <summary>Consume a native result whose data is <c>true</c> or <c>false</c>.</summary>
        private static bool ConsumeBool(FfiResult result) => ConsumeResult(result) == "true";

        /// <summary>Encode <paramref name="s"/> as a null-terminated UTF-8 byte array.</summary>
        internal static byte[] Utf8Z(string s)
        {
            int len = Encoding.UTF8.GetByteCount(s);
            byte[] buf = new byte[len + 1]; // +1 for '\0'
            Encoding.UTF8.GetBytes(s, 0, s.Length, buf, 0);
            return buf; // buf[len] is already 0
        }

        /// <summary>
        /// Parse <c>{"keys":{...},"latest_version":...}</c> from extract/decrypt_events JSON.
        /// </summary>
        private static ConversationKeyBundle ParseConversationKeyBundle(JsonElement root)
        {
            var keysEl = root.GetProperty("keys");
            var keys = new Dictionary<string, byte[]>();
            foreach (var prop in keysEl.EnumerateObject())
                keys[prop.Name] = Convert.FromBase64String(prop.Value.GetString()!);

            string? latest = null;
            if (root.TryGetProperty("latest_version", out var lv) && lv.ValueKind == JsonValueKind.String)
                latest = lv.GetString();

            return new ConversationKeyBundle { Keys = keys, LatestVersion = latest };
        }

        // State

        /// <summary>True when both identity and signing keys are loaded in memory.</summary>
        public bool IsUnlocked
        {
            get
            {
                ThrowIfDisposed();
                bool unlocked = ConsumeBool(NativeMethods.chat_xdk_is_unlocked(_handle));
                GC.KeepAlive(this);
                return unlocked;
            }
        }

        /// <summary>True when the identity key is loaded (sufficient for decryption).</summary>
        public bool HasIdentityKey
        {
            get
            {
                ThrowIfDisposed();
                bool loaded = ConsumeBool(NativeMethods.chat_xdk_has_identity_key(_handle));
                GC.KeepAlive(this);
                return loaded;
            }
        }

        /// <summary>
        /// When <paramref name="reject"/> is true — the default — <see cref="DecryptEvent"/>
        /// throws <see cref="ChatXdkException"/> for any signed event whose signature cannot
        /// be verified (invalid, missing, or no matching signing key) instead of returning
        /// it with <c>verified: false</c>.
        /// </summary>
        public void SetRejectUnverified(bool reject)
        {
            ThrowIfDisposed();
            ConsumeResult(NativeMethods.chat_xdk_set_reject_unverified(_handle, reject ? 1 : 0));
            GC.KeepAlive(this);
        }

        /// <summary>
        /// Set the session identity: the owner's user id and signing-key version, used
        /// as the defaults wherever a params class' <c>SenderId</c> / <c>SigningKeyVersion</c>
        /// is left null. A resolved default and an explicitly passed value produce
        /// byte-identical signed output for the same logical inputs. The signing-key
        /// version is the <c>public_key_version</c> returned when the keys were
        /// registered.
        /// </summary>
        public void SetIdentity(SetIdentityParams parameters)
        {
            ThrowIfDisposed();
            ArgumentNullException.ThrowIfNull(parameters);
            var json = ParamsJson(new Dictionary<string, object?>
            {
                ["user_id"] = parameters.UserId,
                ["signing_key_version"] = parameters.SigningKeyVersion,
            });
            var jsonBytes = Utf8Z(json);
            fixed (byte* jsonPtr = jsonBytes)
                ConsumeResult(NativeMethods.chat_xdk_set_identity(_handle, jsonPtr));
            GC.KeepAlive(this);
        }

        /// <summary>
        /// Enable or disable the conversation-key cache (off by default). While enabled,
        /// <see cref="DecryptEvents"/> caches, per conversation, the key whose key change
        /// carried a valid signature at the highest version seen, and the encrypt methods
        /// resolve a null <c>ConversationKey</c>/<c>ConversationKeyVersion</c> pair from it.
        /// Disabling clears the cache.
        /// </summary>
        public void SetCacheKeys(bool enabled)
        {
            ThrowIfDisposed();
            ConsumeResult(NativeMethods.chat_xdk_set_cache_keys(_handle, enabled ? 1 : 0));
            GC.KeepAlive(this);
        }

        /// <summary>
        /// Store signing keys to use when a decrypt call's params leave <c>SigningKeys</c>
        /// null (or empty). Only this explicit call populates the store — a key carried inside
        /// an event is never trusted for verification. Each call replaces the previous set.
        /// </summary>
        public void SetSigningKeys(IReadOnlyList<SigningKeyEntry> keys)
        {
            ThrowIfDisposed();
            var json = JsonSerializer.Serialize(keys, JsonOpts);
            var jsonBytes = Utf8Z(json);
            fixed (byte* jsonPtr = jsonBytes)
                ConsumeResult(NativeMethods.chat_xdk_set_signing_keys(_handle, jsonPtr));
            GC.KeepAlive(this);
        }

        private void ConfigureFeatures(string endpoint, TimeSpan timeout)
        {
            var endpointBytes = Utf8Z(endpoint);
            fixed (byte* endpointPtr = endpointBytes)
                ConsumeResult(NativeMethods.chat_xdk_internal_feature_configure(
                    _handle, endpointPtr, (ulong)timeout.TotalMilliseconds));
            GC.KeepAlive(this);
        }

        /// <summary>
        /// Start this chat's one read of the feature switches: the GET to perform as JSON, or
        /// an empty string when the chat takes the answer of a GET already in flight.
        /// </summary>
        internal string StartFeatures()
        {
            var json = ConsumeResult(NativeMethods.chat_xdk_internal_feature_start(_handle));
            GC.KeepAlive(this);
            return json;
        }

        /// <summary>Clear all key material from memory without touching Juicebox.</summary>
        public void Lock()
        {
            ThrowIfDisposed();
            ConsumeResult(NativeMethods.chat_xdk_lock(_handle));
            GC.KeepAlive(this);
        }

        // Juicebox lifecycle

        /// <summary>
        /// Set or replace the Juicebox configuration: on first boot, for a chat created
        /// without one, or whenever the X API issues fresh short-lived auth tokens.
        /// </summary>
        public void UpdateConfig(string configJson)
        {
            ThrowIfDisposed();
            var cfg = Utf8Z(configJson);
            fixed (byte* cfgPtr = cfg)
                ConsumeResult(NativeMethods.chat_xdk_update_config(_handle, cfgPtr));
            GC.KeepAlive(this);
        }

        /// <summary>
        /// Register the SDK's keys with Juicebox under <paramref name="pin"/> (first-time
        /// setup). Call <see cref="GenerateKeypairs"/> and POST the result to the X API first,
        /// then call this to persist the keys under the user's PIN. Needs a chat created with
        /// a Juicebox configuration.
        /// </summary>
        /// <param name="pin">The user's PIN, as bytes the SDK never copies to a string, so you
        /// can zero the array once the call returns.</param>
        /// <returns>The user's public keys to upload to the X API.</returns>
        public PublicKeys Setup(byte[] pin)
        {
            ThrowIfDisposed();
            ArgumentNullException.ThrowIfNull(pin);
            string json;
            fixed (byte* pinPtr = pin)
                json = ConsumeResult(NativeMethods.chat_xdk_setup(_handle, pinPtr, (nuint)pin.Length));
            GC.KeepAlive(this);
            return JsonSerializer.Deserialize<PublicKeys>(json, JsonOpts)!;
        }

        /// <summary>
        /// Recover keys from Juicebox with <paramref name="pin"/> and load them into memory.
        /// Call on every startup after the user enters their PIN. A wrong PIN throws a
        /// <see cref="ChatXdkException"/> of kind <see cref="ChatXdkErrorKind.InvalidPin"/>.
        /// </summary>
        /// <param name="pin">The user's PIN, as bytes the SDK never copies to a string, so you
        /// can zero the array once the call returns.</param>
        public void Unlock(byte[] pin)
        {
            ThrowIfDisposed();
            ArgumentNullException.ThrowIfNull(pin);
            fixed (byte* pinPtr = pin)
                ConsumeResult(NativeMethods.chat_xdk_unlock(_handle, pinPtr, (nuint)pin.Length));
            GC.KeepAlive(this);
        }

        /// <summary>
        /// Delete the user's keys from Juicebox and lock the SDK.
        /// Warning: Irreversible — the user loses access to their encrypted message history.
        /// </summary>
        public void Delete()
        {
            ThrowIfDisposed();
            ConsumeResult(NativeMethods.chat_xdk_delete(_handle));
            GC.KeepAlive(this);
        }

        /// <summary>
        /// Re-register keys under a new PIN, unlocking with the old one first. Both PINs are
        /// bytes you can zero once the call returns.
        /// </summary>
        public void ChangePin(byte[] oldPin, byte[] newPin)
        {
            ThrowIfDisposed();
            ArgumentNullException.ThrowIfNull(oldPin);
            ArgumentNullException.ThrowIfNull(newPin);
            fixed (byte* oldPtr = oldPin)
            fixed (byte* newPtr = newPin)
                ConsumeResult(NativeMethods.chat_xdk_change_pin(
                    _handle, oldPtr, (nuint)oldPin.Length, newPtr, (nuint)newPin.Length));
            GC.KeepAlive(this);
        }

        /// <summary><see cref="Setup"/> on the thread pool.</summary>
        public Task<PublicKeys> SetupAsync(byte[] pin) => Task.Run(() => Setup(pin));

        /// <summary><see cref="Unlock"/> on the thread pool.</summary>
        public Task UnlockAsync(byte[] pin) => Task.Run(() => Unlock(pin));

        /// <summary><see cref="Delete"/> on the thread pool.</summary>
        public Task DeleteAsync() => Task.Run(Delete);

        /// <summary><see cref="ChangePin"/> on the thread pool.</summary>
        public Task ChangePinAsync(byte[] oldPin, byte[] newPin) => Task.Run(() => ChangePin(oldPin, newPin));

        // Key management

        /// <summary>
        /// Generate new identity + signing keypairs and return the registration payload.
        /// POST the payload to <c>POST /2/users/:id/public_keys</c> before calling
        /// <see cref="Setup"/>. No signing-key version is set: after registering the keys,
        /// call <see cref="SetIdentity"/> with the <c>public_key_version</c> the
        /// registration returns.
        /// </summary>
        public PublicKeyRegistrationPayload GenerateKeypairs()
        {
            ThrowIfDisposed();
            var json = ConsumeResult(NativeMethods.chat_xdk_generate_keypairs(_handle));
            GC.KeepAlive(this);
            return JsonSerializer.Deserialize<PublicKeyRegistrationPayload>(json, JsonOpts)!;
        }

        /// <summary>Get the user's current public keys (requires keys to be loaded).</summary>
        public PublicKeys GetPublicKeys()
        {
            ThrowIfDisposed();
            var json = ConsumeResult(NativeMethods.chat_xdk_get_public_keys(_handle));
            GC.KeepAlive(this);
            return JsonSerializer.Deserialize<PublicKeys>(json, JsonOpts)!;
        }

        /// <summary>
        /// Get the fingerprint of the loaded identity public key.
        /// Returns a URL-safe base64 SHA-256 of the SPKI-encoded key —
        /// suitable for out-of-band verification by the user.
        /// </summary>
        public string GetPublicKeyFingerprint()
        {
            ThrowIfDisposed();
            var fingerprint = ConsumeResult(NativeMethods.chat_xdk_get_public_key_fingerprint(_handle));
            GC.KeepAlive(this);
            return fingerprint;
        }

        /// <summary>
        /// Export private keys as raw bytes for a secure backup: 32 bytes for the identity
        /// key, 64 with the signing key. Throws a <see cref="ChatXdkException"/> of kind
        /// <see cref="ChatXdkErrorKind.InvalidState"/> when no identity key is loaded.
        /// Warning: These are raw secret key bytes — store with extreme care.
        /// </summary>
        public byte[] ExportKeys()
        {
            ThrowIfDisposed();
            var b64 = ConsumeResult(NativeMethods.chat_xdk_export_keys(_handle));
            GC.KeepAlive(this);
            return Convert.FromBase64String(b64);
        }

        /// <summary>
        /// Import private keys from the byte array <see cref="ExportKeys"/> produced: 32 bytes
        /// (identity only) or 64 bytes (identity + signing). When
        /// <see cref="ImportKeysParams.SigningKeyVersion"/> is set (the <c>public_key_version</c>
        /// returned when the keys were registered), it is recorded as well, so participant-key
        /// filtering and the session signing-key version are set in one call. Without it, no
        /// signing-key version is set. The key bytes are passed to the native side directly,
        /// never copied into a string.
        /// </summary>
        public void ImportKeys(ImportKeysParams parameters)
        {
            ThrowIfDisposed();
            ArgumentNullException.ThrowIfNull(parameters);
            var keys = parameters.Keys ?? Array.Empty<byte>();
            var json = ParamsJson(new Dictionary<string, object?>
            {
                ["signing_key_version"] = parameters.SigningKeyVersion,
            });
            var jsonBytes = Utf8Z(json);
            fixed (byte* jsonPtr = jsonBytes)
            {
                // A zero-length array pins to a null pointer on some CLRs; the
                // native side treats NULL + length 0 as an empty key blob.
                if (keys.Length == 0)
                {
                    ConsumeResult(NativeMethods.chat_xdk_import_keys(_handle, null, 0, jsonPtr));
                }
                else
                {
                    fixed (byte* keysPtr = keys)
                        ConsumeResult(NativeMethods.chat_xdk_import_keys(
                            _handle, keysPtr, (nuint)keys.Length, jsonPtr));
                }
            }
            GC.KeepAlive(this);
        }

        // Event decryption

        /// <summary>
        /// Extract and decrypt conversation keys from raw <c>KeyChange</c> event strings.
        /// </summary>
        /// <param name="events">
        /// Base64-encoded raw event strings received from the webhook.
        /// Pass only <c>KeyChange</c> events — other event types are ignored.
        /// </param>
        /// <returns>
        /// Decrypted keys and <see cref="ConversationKeyBundle.LatestVersion"/>.
        /// Pass <see cref="ConversationKeyBundle.Keys"/> (or the whole bundle) to <see cref="DecryptEvent"/>.
        /// </returns>
        public ConversationKeyBundle ExtractConversationKeys(IEnumerable<string> events)
        {
            ThrowIfDisposed();
            var eventsJson = JsonSerializer.Serialize(new List<string>(events), JsonOpts);
            var eventsBytes = Utf8Z(eventsJson);
            string resultJson;
            fixed (byte* eventsPtr = eventsBytes)
                resultJson = ConsumeResult(NativeMethods.chat_xdk_extract_conversation_keys(_handle, eventsPtr));
            GC.KeepAlive(this);

            using var doc = JsonDocument.Parse(resultJson);
            return ParseConversationKeyBundle(doc.RootElement);
        }

        /// <summary>
        /// Decrypt a webhook event and return it as a <see cref="JsonElement"/>.
        /// Under the default reject-unverified policy, a signed event with no usable signing
        /// key (passed or stored via <see cref="SetSigningKeys"/>) throws; only after
        /// <see cref="SetRejectUnverified"/>(false) are such events returned with
        /// <c>verified: false</c>.
        /// </summary>
        /// <returns>
        /// A <see cref="JsonElement"/> with a <c>"type"</c> field indicating the event kind
        /// (<c>"Message"</c>, <c>"KeyChange"</c>, <c>"GroupChange"</c>, etc.).
        /// </returns>
        public JsonElement DecryptEvent(DecryptEventParams parameters)
        {
            ThrowIfDisposed();
            ArgumentNullException.ThrowIfNull(parameters);
            var json = ParamsJson(new Dictionary<string, object?>
            {
                ["event_b64"] = parameters.EventB64,
                ["conversation_keys"] = ConversationKeysB64(parameters.ConversationKeys),
                ["signing_keys"] = parameters.SigningKeys,
            });
            var jsonBytes = Utf8Z(json);
            string resultJson;
            fixed (byte* jsonPtr = jsonBytes)
                resultJson = ConsumeResult(NativeMethods.chat_xdk_decrypt_event(_handle, jsonPtr));
            GC.KeepAlive(this);

            using var doc = JsonDocument.Parse(resultJson);
            return doc.RootElement.Clone();
        }

        /// <summary>Encode a version → key map as <c>{ "version": "base64", ... }</c>.</summary>
        private static Dictionary<string, string> ConversationKeysB64(IReadOnlyDictionary<string, byte[]>? conversationKeys)
        {
            var convKeysB64 = new Dictionary<string, string>();
            if (conversationKeys != null)
                foreach (var (version, key) in conversationKeys)
                    convKeysB64[version] = Convert.ToBase64String(key);
            return convKeysB64;
        }

        /// <summary>
        /// Decrypt a batch of webhook events in one call.
        /// Keys are extracted from <c>KeyChange</c> events in the batch; failures are recorded
        /// in <see cref="DecryptEventsResult.Errors"/> — this method never throws per-event.
        /// </summary>
        public DecryptEventsResult DecryptEvents(DecryptEventsParams parameters)
        {
            ThrowIfDisposed();
            ArgumentNullException.ThrowIfNull(parameters);
            var json = ParamsJson(new Dictionary<string, object?>
            {
                ["events"] = parameters.Events ?? Array.Empty<string>(),
                ["signing_keys"] = parameters.SigningKeys,
            });
            var jsonBytes = Utf8Z(json);
            string resultJson;
            fixed (byte* jsonPtr = jsonBytes)
                resultJson = ConsumeResult(NativeMethods.chat_xdk_decrypt_events(_handle, jsonPtr));
            GC.KeepAlive(this);

            using var doc = JsonDocument.Parse(resultJson);
            var root = doc.RootElement;

            var events = new List<DecryptedEvent>();
            foreach (var el in root.GetProperty("events").EnumerateArray())
            {
                var eventEl = el.GetProperty("event");
                string? orig = null;
                if (el.TryGetProperty("original_b64", out var ob) && ob.ValueKind == JsonValueKind.String)
                    orig = ob.GetString();
                events.Add(new DecryptedEvent
                {
                    Event = eventEl.Clone(),
                    OriginalB64 = orig,
                });
            }

            var bundle = ParseConversationKeyBundle(root.GetProperty("conversation_keys"));

            var errors = new Dictionary<string, string>();
            foreach (var prop in root.GetProperty("errors").EnumerateObject())
                errors[prop.Name] = prop.Value.GetString() ?? "";

            return new DecryptEventsResult
            {
                Events = events,
                ConversationKeys = bundle,
                Errors = errors,
            };
        }

        /// <summary>
        /// Prepare a signed conversation-key change, ready to send to the X API.
        /// Use this to start a one-to-one or rotate an existing conversation's key
        /// (one-to-one or group). Creating a group or adding members requires a paired
        /// group signature as well — use <see cref="PrepareGroupCreate"/> or
        /// <see cref="PrepareGroupMembersChange"/> for those.
        /// Leave <see cref="ConversationKeyChangeParams.ConversationId"/> null for a
        /// one-to-one to derive the canonical id from the two participants; pass the
        /// existing id for a group rotation.
        /// </summary>
        public PreparedConversationChange PrepareConversationKeyChange(ConversationKeyChangeParams parameters)
        {
            ThrowIfDisposed();
            return CallPrepareEndpoint(
                BuildPrepareConversationKeyChangeJson(parameters),
                NativeMethods.chat_xdk_prepare_conversation_key_change);
        }

        /// <summary>
        /// Prepare a signed group member-add change for the updated roster, ready to
        /// send to the X API.
        /// Use this when adding members to an existing group. Creating the group is
        /// <see cref="PrepareGroupCreate"/>; a key rotation without a roster change is
        /// <see cref="PrepareConversationKeyChange"/>.
        /// Emits two action signatures: a conversation-key change and the member add.
        /// The current title and description are plaintext: the call encrypts each under the
        /// new conversation key, signs the ciphertext, and returns it as
        /// <see cref="PreparedConversationChange.EncryptedTitle"/> and
        /// <see cref="PreparedConversationChange.EncryptedDescription"/>. The current avatar URL
        /// is signed as is.
        /// </summary>
        public PreparedConversationChange PrepareGroupMembersChange(GroupMembersChangeParams parameters)
        {
