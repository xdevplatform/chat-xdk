using System;
using System.Collections.Generic;
using System.Runtime.InteropServices;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;

namespace ChatXdk
{
    /// <summary>
    /// The main X Chat encryption SDK.
    ///
    /// <para>Wraps the Rust <c>chat_xdk_core</c> library via P/Invoke and provides
    /// the operations exposed by the SDK:</para>
    /// <list type="bullet">
    ///   <item>Key generation and Juicebox-backed storage (<see cref="GenerateKeypairs"/>, <see cref="Setup"/>, <see cref="Unlock"/>)</item>
    ///   <item>Event decryption (<see cref="ExtractConversationKeys"/>, <see cref="DecryptEvents"/>, <see cref="DecryptEvent"/>)</item>
    ///   <item>Signed conversation-key changes (<see cref="PrepareConversationKeyChange"/>, <see cref="PrepareGroupCreate"/>, <see cref="PrepareGroupMembersChange"/>)</item>
    ///   <item>UTF-8 metadata encryption with the conversation key (<see cref="Encrypt"/>, <see cref="Decrypt"/>)</item>
    ///   <item>Message / reaction / reply encryption (<see cref="EncryptMessage"/>, etc.)</item>
    ///   <item>Media streaming encryption (<see cref="EncryptStream"/>, <see cref="DecryptStream"/>)</item>
    ///   <item>Stateless helpers on <see cref="ChatXdkUtilities"/> (base64/hex, MIME, image dimensions)</item>
    /// </list>
    ///
    /// <para>Always <see cref="Dispose"/> the instance when finished to release native resources.</para>
    ///
    /// <para>Not thread-safe: do not share one instance across threads without external
    /// synchronization. Mutating operations (<see cref="Setup"/>, <see cref="Unlock"/>,
    /// <see cref="Delete"/>, <see cref="ChangePin"/>, <see cref="UpdateConfig"/>,
    /// <see cref="SetRejectUnverified"/>,
    /// <see cref="SetIdentity"/>, <see cref="SetCacheKeys"/>, <see cref="SetSigningKeys"/>)
    /// must not race decrypt or any other call on the same instance.</para>
    /// </summary>
    /// <example>
    /// <code>
    /// using var chat = new Chat();
    /// chat.Unlock("2580", juiceboxConfigJson);
    /// chat.SetIdentity(myUserId, mySigningKeyVersion); // session identity, once
    /// chat.SetCacheKeys(true);                         // opt-in conversation-key cache
    /// chat.SetSigningKeys(participantSigningKeys);     // default verification keys
    ///
    /// // Decrypt incoming events (keys are cached from verified KeyChange events)
    /// var result = chat.DecryptEvents(eventsB64);
    /// var evt = chat.DecryptEvent(eventB64);
    /// Console.WriteLine(evt.GetProperty("type").GetString()); // "Message", "KeyChange", …
    ///
    /// // Send a message — identity and conversation key resolve from the session
    /// var payload = chat.EncryptMessage(new EncryptMessageParams(convId, "Hello from .NET!"));
    /// // The SDK generates the message id; read it back from payload.MessageId.
    /// // POST payload fields to the X API…
    /// </code>
    /// </example>
    public sealed unsafe class Chat : IDisposable
    {
        // Pointer to the native ChatHandle allocated by chat_xdk_new().
        // ChatHandle is generated by csbindgen at the ChatXdk namespace level.
        private ChatHandle* _handle;
        private bool _disposed;

        // Shared JSON options: ignore nulls on write. Property names are
        // snake_case via explicit [JsonPropertyName] attributes on each DTO,
        // not a naming policy here.
        private static readonly JsonSerializerOptions JsonOpts = new()
        {
            DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        };

        /// <summary>
        /// Create a new Chat SDK instance.
        /// </summary>
        /// <exception cref="InvalidOperationException">
        /// Thrown if the native library fails to initialise (e.g. missing shared library).
        /// </exception>
        public Chat()
        {
            _handle = NativeMethods.chat_xdk_new();
            if (_handle == null)
                throw new InvalidOperationException(
                    "chat_xdk_new() returned NULL — ensure the native library " +
                    "(chat_xdk_dotnet.dylib / .so / .dll) is on the library search path.");
        }

        /// <summary>
        /// Finalizer — ensures the native handle is freed even if <see cref="Dispose"/>
        /// is never called explicitly (e.g. the object is forgotten without <c>using</c>).
        /// An object becomes finalizable as soon as its last use passes — even while
        /// one of its methods is still executing native code — so every method that
        /// passes <c>_handle</c> across the P/Invoke boundary calls
        /// <see cref="GC.KeepAlive(object)"/> on <c>this</c> after the call, keeping
        /// this finalizer from freeing the handle mid-call.
        /// </summary>
        ~Chat() => Dispose(disposing: false);

        /// <inheritdoc/>
        public void Dispose()
        {
            Dispose(disposing: true);
            GC.SuppressFinalize(this);
        }

        private void Dispose(bool disposing)
        {
            // Both the finalizer and Dispose() paths end here.
            // We only need to free the unmanaged handle; there are no managed resources.
            if (!_disposed)
            {
                _disposed = true;
                if (_handle != null)
                {
                    NativeMethods.chat_xdk_free(_handle);
                    _handle = null;
                }
            }
        }

        // Internal helpers

        private void ThrowIfDisposed()
        {
            if (_disposed) throw new ObjectDisposedException(nameof(Chat));
        }

        /// <summary>
        /// Consume a native <see cref="FfiResult"/>: free both pointers,
        /// throw <see cref="ChatXdkException"/> on error, return the data string on success.
        /// Returns an empty string for void-OK results.
        /// </summary>
        internal static string ConsumeResult(FfiResult result)
        {
            // Always marshal both strings before freeing — avoids a double-free
            // if the error branch short-circuits.
            string? data = result.data != null
                ? Marshal.PtrToStringUTF8((IntPtr)result.data)
                : null;
            string? error = result.error != null
                ? Marshal.PtrToStringUTF8((IntPtr)result.error)
                : null;

            if (result.data != null) NativeMethods.chat_xdk_free_string(result.data);
            if (result.error != null) NativeMethods.chat_xdk_free_string(result.error);

            if (error != null) throw new ChatXdkException(error);
            return data ?? "";
        }

        /// <summary>Encode <paramref name="s"/> as a null-terminated UTF-8 byte array.</summary>
        internal static byte[] Utf8Z(string s)
        {
            int len = Encoding.UTF8.GetByteCount(s);
            byte[] buf = new byte[len + 1]; // +1 for '\0'
            Encoding.UTF8.GetBytes(s, 0, s.Length, buf, 0);
            return buf; // buf[len] is already 0
        }

        /// <summary>
        /// Parse <c>{"keys":{...},"latest_version":...}</c> from extract/decrypt_events JSON.
        /// </summary>
        private static ConversationKeyBundle ParseConversationKeyBundle(JsonElement root)
        {
            var keysEl = root.GetProperty("keys");
            var keys = new Dictionary<string, byte[]>();
            foreach (var prop in keysEl.EnumerateObject())
                keys[prop.Name] = Convert.FromBase64String(prop.Value.GetString()!);

            string? latest = null;
            if (root.TryGetProperty("latest_version", out var lv) && lv.ValueKind == JsonValueKind.String)
                latest = lv.GetString();

            return new ConversationKeyBundle { Keys = keys, LatestVersion = latest };
        }

        // State

        /// <summary>True when both identity and signing keys are loaded in memory.</summary>
        public bool IsUnlocked
        {
            get
            {
                ThrowIfDisposed();
                bool unlocked = NativeMethods.chat_xdk_is_unlocked(_handle) == 1;
                GC.KeepAlive(this);
                return unlocked;
            }
        }

        /// <summary>True when the identity key is loaded (sufficient for decryption).</summary>
        public bool HasIdentityKey
        {
            get
            {
                ThrowIfDisposed();
                bool loaded = NativeMethods.chat_xdk_has_identity_key(_handle) == 1;
                GC.KeepAlive(this);
                return loaded;
            }
        }

        /// <summary>
        /// When <paramref name="reject"/> is true — the default — <see cref="DecryptEvent"/>
        /// throws <see cref="ChatXdkException"/> for any signed event whose signature cannot
        /// be verified (invalid, missing, or no matching signing key) instead of returning
        /// it with <c>verified: false</c>.
        /// </summary>
        public void SetRejectUnverified(bool reject)
        {
            ThrowIfDisposed();
            NativeMethods.chat_xdk_set_reject_unverified(_handle, reject ? 1 : 0);
            GC.KeepAlive(this);
        }

        /// <summary>
        /// Set the session identity: the owner's user id and signing-key version, used
        /// as the defaults wherever a params class' <c>SenderId</c> / <c>SigningKeyVersion</c>
        /// is left null. A resolved default and an explicitly passed value produce
        /// byte-identical signed output for the same logical inputs.
        /// </summary>
        public void SetIdentity(string userId, string signingKeyVersion)
        {
            ThrowIfDisposed();
            var user = Utf8Z(userId);
            var ver = Utf8Z(signingKeyVersion);
            fixed (byte* userPtr = user)
            fixed (byte* verPtr = ver)
                ConsumeResult(NativeMethods.chat_xdk_set_identity(_handle, userPtr, verPtr));
            GC.KeepAlive(this);
        }

        /// <summary>
        /// Enable or disable the conversation-key cache (off by default). While enabled,
        /// <see cref="DecryptEvents"/> caches, per conversation, the key whose key change
        /// carried a valid signature at the highest version seen, and the encrypt methods
        /// resolve a null <c>ConversationKey</c>/<c>ConversationKeyVersion</c> pair from it.
        /// Disabling clears the cache.
        /// </summary>
        public void SetCacheKeys(bool enabled)
        {
            ThrowIfDisposed();
            NativeMethods.chat_xdk_set_cache_keys(_handle, enabled ? 1 : 0);
            GC.KeepAlive(this);
        }

        /// <summary>
        /// Store signing keys to use when a decrypt call omits its <c>signingKeys</c>
        /// argument. Only this explicit call populates the store — a key carried inside
        /// an event is never trusted for verification. Each call replaces the previous set.
        /// </summary>
        public void SetSigningKeys(IReadOnlyList<SigningKeyEntry> keys)
        {
            ThrowIfDisposed();
            var json = JsonSerializer.Serialize(keys, JsonOpts);
            var jsonBytes = Utf8Z(json);
            fixed (byte* jsonPtr = jsonBytes)
                ConsumeResult(NativeMethods.chat_xdk_set_signing_keys(_handle, jsonPtr));
            GC.KeepAlive(this);
        }

        /// <summary>Clear all key material from memory without touching Juicebox.</summary>
        public void Lock()
        {
            ThrowIfDisposed();
            NativeMethods.chat_xdk_lock(_handle);
            GC.KeepAlive(this);
        }

        // Juicebox lifecycle

        /// <summary>
        /// Update the Juicebox configuration — call this whenever the X API
        /// issues fresh short-lived auth tokens.
        /// </summary>
        public void UpdateConfig(string configJson)
        {
            ThrowIfDisposed();
            var cfg = Utf8Z(configJson);
            fixed (byte* cfgPtr = cfg)
                ConsumeResult(NativeMethods.chat_xdk_update_config(_handle, cfgPtr));
            GC.KeepAlive(this);
        }

        /// <summary>
        /// Register the SDK's keys with Juicebox (first-time setup).
        /// Call <see cref="GenerateKeypairs"/> and POST the result to the X API first,
        /// then call this to persist the keys under the user's PIN.
        /// </summary>
        /// <param name="pin">User-chosen PIN.</param>
        /// <param name="configJson">Juicebox configuration JSON from the X API.</param>
        /// <returns>The user's public keys to upload to the X API.</returns>
        public PublicKeys Setup(string pin, string configJson)
        {
            ThrowIfDisposed();
            var pinBytes = Utf8Z(pin);
            var cfgBytes = Utf8Z(configJson);
            string json;
            fixed (byte* pinPtr = pinBytes)
            fixed (byte* cfgPtr = cfgBytes)
                json = ConsumeResult(NativeMethods.chat_xdk_setup(_handle, pinPtr, cfgPtr));
            GC.KeepAlive(this);
            return JsonSerializer.Deserialize<PublicKeys>(json, JsonOpts)!;
        }

        /// <summary>
        /// Recover keys from Juicebox and load them into memory.
        /// Call on every startup after the user enters their PIN.
        /// </summary>
        /// <param name="pin">The user's PIN.</param>
        /// <param name="configJson">Juicebox configuration JSON from the X API.</param>
        public void Unlock(string pin, string configJson)
        {
            ThrowIfDisposed();
            var pinBytes = Utf8Z(pin);
            var cfgBytes = Utf8Z(configJson);
            fixed (byte* pinPtr = pinBytes)
            fixed (byte* cfgPtr = cfgBytes)
                ConsumeResult(NativeMethods.chat_xdk_unlock(_handle, pinPtr, cfgPtr));
            GC.KeepAlive(this);
        }

        /// <summary>
        /// Delete the user's keys from Juicebox and lock the SDK.
        /// Warning: Irreversible — the user loses access to their encrypted message history.
        /// </summary>
        public void Delete()
        {
            ThrowIfDisposed();
            ConsumeResult(NativeMethods.chat_xdk_delete(_handle));
            GC.KeepAlive(this);
        }

        /// <summary>Re-register keys under a new PIN.</summary>
        public void ChangePin(string oldPin, string newPin)
        {
            ThrowIfDisposed();
            var oldBytes = Utf8Z(oldPin);
            var newBytes = Utf8Z(newPin);
            fixed (byte* oldPtr = oldBytes)
            fixed (byte* newPtr = newBytes)
                ConsumeResult(NativeMethods.chat_xdk_change_pin(_handle, oldPtr, newPtr));
            GC.KeepAlive(this);
        }

