            var json = ConsumeResult(NativeMethods.chat_xdk_generate_keypairs(_handle));
            GC.KeepAlive(this);
            return JsonSerializer.Deserialize<PublicKeyRegistrationPayload>(json, JsonOpts)!;
        }

        /// <summary>Get the user's current public keys (requires keys to be loaded).</summary>
