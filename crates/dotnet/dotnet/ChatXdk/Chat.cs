        // Signing / verification

        /// <summary>
        /// Sign arbitrary data with the signing key.
        /// </summary>
        /// <param name="data">Bytes to sign. May be empty but not null.</param>
        /// <returns>64-byte ECDSA P-256 signature.</returns>
        public byte[] Sign(byte[] data)
        {
            ThrowIfDisposed();
            if (data == null) throw new ArgumentNullException(nameof(data));

            string sigB64;
            // For zero-length arrays, fixed can yield a null pointer on some CLR
            // implementations. Pass null explicitly — the Rust side guards data_len == 0.
            if (data.Length == 0)
            {
                sigB64 = ConsumeResult(NativeMethods.chat_xdk_sign(_handle, null, 0));
            }
            else
            {
                fixed (byte* dataPtr = data)
                    sigB64 = ConsumeResult(NativeMethods.chat_xdk_sign(_handle, dataPtr, (nuint)data.Length));
            }
            GC.KeepAlive(this);
            return Convert.FromBase64String(sigB64);
        }

        /// <summary>Verify an ECDSA signature.</summary>
        /// <param name="publicKeyB64">Base64-encoded signing public key (SEC1 or SPKI).</param>
        /// <param name="signature">Raw signature bytes from <see cref="Sign"/>.</param>
        /// <param name="data">The original signed data.</param>
        /// <returns><see langword="true"/> if the signature is valid, <see langword="false"/> if invalid.</returns>
        /// <exception cref="ChatXdkException">
        /// Thrown when the SDK returns an error (e.g. keys not loaded, malformed public key).
        /// An SDK error is always thrown, never returned as a <see langword="false"/> result.
        /// </exception>
        public bool Verify(string publicKeyB64, byte[] signature, byte[] data)
        {
            ThrowIfDisposed();
            if (signature == null) throw new ArgumentNullException(nameof(signature));
            if (data == null) throw new ArgumentNullException(nameof(data));

            var sigB64 = Convert.ToBase64String(signature);
            var pkBytes = Utf8Z(publicKeyB64);
            var sigBytes = Utf8Z(sigB64);
            int rc;

            // data may be empty; handle the zero-length case explicitly so the
            // fixed statement always has a valid (non-null) pinned pointer.
            if (data.Length == 0)
            {
                fixed (byte* pkPtr = pkBytes)
                fixed (byte* sigPtr = sigBytes)
                    rc = NativeMethods.chat_xdk_verify(_handle, pkPtr, sigPtr, null, 0);
            }
            else
            {
                fixed (byte* pkPtr = pkBytes)
                fixed (byte* sigPtr = sigBytes)
                fixed (byte* dataPtr = data)
                    rc = NativeMethods.chat_xdk_verify(_handle, pkPtr, sigPtr, dataPtr, (nuint)data.Length);
            }
            GC.KeepAlive(this);

            return rc switch
            {
                1 => true,
                0 => false,
                // -1: SDK locked, invalid public key format, or bad signature base64.
                // We throw on a -1 error code.
                _ => throw new ChatXdkException(
                    "Signature verification error — ensure the SDK is unlocked and the public key is valid."),
            };
        }

        /// <summary>
        /// Verify that a signing key is authentically bound to an identity key.
        /// Call this when you receive another user's public keys from the X API
        /// to detect server-side key substitution. All arguments are base64.
        /// </summary>
        public bool VerifyKeyBinding(string identityPublicKeyB64, string signingPublicKeyB64, string identityPublicKeySignatureB64)
        {
            ThrowIfDisposed();
            var identityBytes = Utf8Z(identityPublicKeyB64);
            var signingBytes = Utf8Z(signingPublicKeyB64);
            var sigBytes = Utf8Z(identityPublicKeySignatureB64);
            int rc;
            fixed (byte* identityPtr = identityBytes)
            fixed (byte* signingPtr = signingBytes)
            fixed (byte* sigPtr = sigBytes)
                rc = NativeMethods.chat_xdk_verify_key_binding(_handle, identityPtr, signingPtr, sigPtr);
            GC.KeepAlive(this);

            return rc switch
            {
                1 => true,
                0 => false,
                _ => throw new ChatXdkException(
                    "Key binding verification error — ensure the inputs are valid base64."),
            };
        }

        /// <summary>
        /// Report whether the loaded identity public key is the key in
        /// <paramref name="publicKeyB64"/>. The X API returns the identity
        /// public key in SPKI/DER encoding while GetPublicKeys returns the
        /// raw SEC1 point; this accepts either encoding, so use it to check
