        // Entities are serialised as [[start, end, "type"], ...] tuples.
        private static object[][] SerialiseEntities(IReadOnlyList<EntityDescriptor> entities)
        {
            var result = new object[entities.Count][];
            for (int i = 0; i < entities.Count; i++)
            {
                var e = entities[i];
                result[i] = new object[] { e.Start, e.End, e.EntityType };
            }
            return result;
        }
