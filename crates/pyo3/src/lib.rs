/// Incremental encryptor for one file of an outgoing message.
///
/// Feed the file with ``push``; call ``finish`` once to emit the final frame.
#[pyclass]
pub struct FileEncryptor {
    inner: Option<chat_xdk_core::FileEncryptor>,
}

#[pymethods]
impl FileEncryptor {
    /// Encrypt a chunk of the file, returning the encrypted bytes available
    /// so far.
    fn push<'py>(&mut self, py: Python<'py>, plaintext: &[u8]) -> PyResult<Bound<'py, PyBytes>> {
        let enc = self.inner.as_mut().ok_or_else(|| {
            PyErr::new::<pyo3::exceptions::PyRuntimeError, _>("file encryptor already finished")
        })?;
        let out = enc.push(plaintext).map_err(to_py_err)?;
        Ok(PyBytes::new(py, &out))
    }

    /// Emit the final frame and consume the encryptor.
    fn finish<'py>(&mut self, py: Python<'py>) -> PyResult<Bound<'py, PyBytes>> {
        let enc = self.inner.take().ok_or_else(|| {
            PyErr::new::<pyo3::exceptions::PyRuntimeError, _>("file encryptor already finished")
        })?;
        let out = enc.finish().map_err(to_py_err)?;
        Ok(PyBytes::new(py, &out))
    }
}

/// Incremental decryptor for one encrypted file.
///
/// Feed the encrypted bytes with ``push``; call ``finish`` once at end of
/// input. ``finish`` raises if the file ended before its final frame
/// (truncation), so callers must not treat bytes from ``push`` as complete
/// until ``finish`` succeeds.
#[pyclass]
pub struct FileDecryptor {
    inner: Option<chat_xdk_core::FileDecryptor>,
}

#[pymethods]
impl FileDecryptor {
    /// Decrypt a chunk of the encrypted file, returning the bytes available
    /// so far.
    fn push<'py>(&mut self, py: Python<'py>, ciphertext: &[u8]) -> PyResult<Bound<'py, PyBytes>> {
        let dec = self.inner.as_mut().ok_or_else(|| {
            PyErr::new::<pyo3::exceptions::PyRuntimeError, _>("file decryptor already finished")
        })?;
        let out = dec.push(ciphertext).map_err(to_py_err)?;
        Ok(PyBytes::new(py, &out))
    }

    /// Decrypt the final frame and consume the decryptor.
    fn finish<'py>(&mut self, py: Python<'py>) -> PyResult<Bound<'py, PyBytes>> {
        let dec = self.inner.take().ok_or_else(|| {
            PyErr::new::<pyo3::exceptions::PyRuntimeError, _>("file decryptor already finished")
        })?;
        let out = dec.finish().map_err(to_py_err)?;
        Ok(PyBytes::new(py, &out))
    }
}

// Feature switches (GET /2/chat/features). A chat reads them when it is
// created: the core decides what to fetch, when to retry and what an answer
// means, and the Python package performs the GET, and each retry, on a thread
// of its own. None of this is API.

static FEATURE_STARTER: pyo3::sync::PyOnceLock<Py<PyAny>> = pyo3::sync::PyOnceLock::new();

/// Start `chat`'s read of the feature switches: hand the GET the core
/// returns, if any, to the starter the package registered. A GET that cannot
/// start fails at once, and the chat keeps every switch off.
fn start_feature_read(py: Python<'_>, chat: &chat_xdk_core::Chat) {
    let Some(fetch) = chat.start_features() else {
        return;
    };
    let started = FEATURE_STARTER.get(py).is_some_and(|starter| {
        starter
            .call1(
                py,
                (
                    fetch.id,
                    fetch.url.as_str(),
                    fetch.timeout_ms as f64 / 1000.0,
                    fetch.max_bytes,
                ),
            )
            .is_ok()
    });
    if !started {
        bindings::abandon_fetch(fetch.id);
    }
}

/// Register the callable that performs a chat's feature GET:
/// ``starter(id, url, timeout_seconds, max_bytes)`` starts it and returns.
#[pyfunction]
#[pyo3(name = "_feature_set_starter")]
fn feature_set_starter(py: Python<'_>, starter: Py<PyAny>) {
    let _ = FEATURE_STARTER.set(py, starter);
}

/// Report the result of the feature GET ``fetch_id``: its HTTP status, 0 when
/// no complete response arrived, and its body. Returns the retry to perform,
/// ``(id, url, timeout_seconds, max_bytes, delay_seconds)``, or ``None``.
#[pyfunction]
#[pyo3(name = "_feature_complete")]
fn feature_complete(
    fetch_id: u64,
    status: u16,
    body: &[u8],
) -> Option<(u64, String, f64, usize, f64)> {
    bindings::complete_fetch(fetch_id, status, body).map(|retry| {
        (
            retry.id,
            retry.url,
            retry.timeout_ms as f64 / 1000.0,
            retry.max_bytes,
            retry.delay_ms as f64 / 1000.0,
        )
    })
}

