//! Python bindings for chat-xdk encryption library.
//!
//! Provides a simple, Pythonic interface to the X Chat SDK.
//!
//! # Quick Start
//!
//! ```python
//! from chat_xdk import Chat, DecryptEventParams, EncryptMessageParams
//!
//! chat = Chat()
//! chat.unlock(pin)
//! chat.set_identity(my_user_id, signing_key_version)
//!
//! # Decrypt an event (returns a dict). `conversation_keys` maps key version
//! # to the raw 32-byte key (from decrypt_events or extract_conversation_keys);
//! # `signing_keys` is the list of signing-key dicts for the sender.
//! event = chat.decrypt_event(
//!     DecryptEventParams(event_b64, conversation_keys, signing_keys=signing_keys)
//! )
//! print(event["type"])  # "Message", "KeyChange", etc.
//!
//! # Encrypt a message with the raw 32-byte conversation key
//! payload = chat.encrypt_message(
//!     EncryptMessageParams(conversation_id, "Hello!",
//!                          conversation_key=conversation_key,
//!                          conversation_key_version=conversation_key_version)
//! )
//! # payload.message_id (generated by the SDK), payload.encrypted_content, etc.
//! ```

