/// Incremental encryptor for one file of an outgoing message.
///
/// Feed the file with ``push``; call ``finish`` once to emit the final frame.
#[pyclass]
pub struct FileEncryptor {
    inner: Option<chat_xdk_core::FileEncryptor>,
}

#[pymethods]
impl FileEncryptor {
    /// Encrypt a chunk of the file, returning the encrypted bytes available
    /// so far.
    fn push<'py>(&mut self, py: Python<'py>, plaintext: &[u8]) -> PyResult<Bound<'py, PyBytes>> {
        let enc = self.inner.as_mut().ok_or_else(|| {
            PyErr::new::<pyo3::exceptions::PyRuntimeError, _>("file encryptor already finished")
        })?;
        let out = enc.push(plaintext).map_err(to_py_err)?;
        Ok(PyBytes::new(py, &out))
    }

    /// Emit the final frame and consume the encryptor.
    fn finish<'py>(&mut self, py: Python<'py>) -> PyResult<Bound<'py, PyBytes>> {
        let enc = self.inner.take().ok_or_else(|| {
            PyErr::new::<pyo3::exceptions::PyRuntimeError, _>("file encryptor already finished")
        })?;
        let out = enc.finish().map_err(to_py_err)?;
        Ok(PyBytes::new(py, &out))
    }
}

/// Incremental decryptor for one encrypted file.
///
/// Feed the encrypted bytes with ``push``; call ``finish`` once at end of
/// input. ``finish`` raises if the file ended before its final frame
/// (truncation), so callers must not treat bytes from ``push`` as complete
/// until ``finish`` succeeds.
#[pyclass]
pub struct FileDecryptor {
    inner: Option<chat_xdk_core::FileDecryptor>,
}

#[pymethods]
impl FileDecryptor {
    /// Decrypt a chunk of the encrypted file, returning the bytes available
    /// so far.
    fn push<'py>(&mut self, py: Python<'py>, ciphertext: &[u8]) -> PyResult<Bound<'py, PyBytes>> {
        let dec = self.inner.as_mut().ok_or_else(|| {
            PyErr::new::<pyo3::exceptions::PyRuntimeError, _>("file decryptor already finished")
        })?;
        let out = dec.push(ciphertext).map_err(to_py_err)?;
        Ok(PyBytes::new(py, &out))
    }

    /// Decrypt the final frame and consume the decryptor.
    fn finish<'py>(&mut self, py: Python<'py>) -> PyResult<Bound<'py, PyBytes>> {
        let dec = self.inner.take().ok_or_else(|| {
            PyErr::new::<pyo3::exceptions::PyRuntimeError, _>("file decryptor already finished")
        })?;
        let out = dec.finish().map_err(to_py_err)?;
        Ok(PyBytes::new(py, &out))
    }
}

